-- Baseline of the live `public` schema, taken 2026-10-18 with
-- `supabase db dump --schema public`. Supersedes the legacy migrations 001-034
-- (archived in supabase/migrations-legacy/); never apply it to the live database,
-- register it there with `supabase migration repair --status applied 20261018000000`.
--
-- Stripped from the dump so it replays on plain Postgres: session SETs, schema
-- create/comment, OWNER TO, GRANT/REVOKE and ALTER DEFAULT PRIVILEGES (Supabase
-- manages roles and grants), IF NOT EXISTS. Object names are kept verbatim, including
-- legacy ones (aq_grid_pkey, measurements_id_seq, "public.fire_points_id_seq").
-- The rls_auto_enable() event trigger itself is database-level and Supabase-managed,
-- so only its function is included.


CREATE FUNCTION "public"."rls_auto_enable"() RETURNS "event_trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'pg_catalog'
    AS $$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$$;

